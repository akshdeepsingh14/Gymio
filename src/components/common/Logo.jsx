/**
 * Gymio brand mark: the flexed-arm "G" artwork.
 * Foreground and background colours follow the theme, so it inverts by itself.
 *
 * `decorative` hides it from screen readers when text sits next to it.
 */
export function LogoMark({ className, decorative = false }) {
  return (
    <svg
      viewBox="54 24 281 281"
      xmlns="http://www.w3.org/2000/svg"
      role={decorative ? undefined : "img"}
      aria-label={decorative ? undefined : "Gymio"}
      aria-hidden={decorative ? "true" : undefined}
      className={cn("size-10 shrink-0", className)}
      fill="none"
    >
      <rect x="54" y="24" width="281" height="281" className="fill-background" />

      <path
        d={LOGO_PATH}
        fillRule="evenodd"
        stroke="none"
        className="fill-foreground"
      />
    </svg>
  );
}

/** Mark + wordmark, links home. On the home page it scrolls to the top instead. */
export function Logo({ className, markClassName }) {
  const { pathname } = useLocation();

  const handleClick = (event) => {
    if (pathname === "/") {
      event.preventDefault();
      scrollToTop();
    }
  };

  return (
    <Link
      to="/"
      onClick={handleClick}
      aria-label="Gymio, go to home"
      className={cn(
        "inline-flex items-center gap-2.5 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring focus-visible:ring-offset-2 focus-visible:ring-offset-background",
        className
      )}
    >
      <LogoMark decorative className={markClassName} />

      <span
        aria-hidden="true"
        className="font-display text-[1.7rem] font-extrabold uppercase leading-none tracking-[0.02em]"
      >
        Gymio
      </span>
    </Link>
  );
}

